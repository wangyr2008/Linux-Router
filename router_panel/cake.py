from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from .core import (
    SYSTEM_COMMAND_TIMEOUT,
    CommandResult,
    atomic_write_text,
    command_exists,
    is_service_active,
    run_command,
)

CAKE_SCRIPT_PATH = Path("/etc/linux-router/cake.sh")
CAKE_SERVICE_NAME = "linux-router-cake.service"
CAKE_TIMER_NAME = "linux-router-cake.timer"
CAKE_SERVICE_PATH = Path("/etc/systemd/system") / CAKE_SERVICE_NAME
CAKE_TIMER_PATH = Path("/etc/systemd/system") / CAKE_TIMER_NAME
# A dedicated IFB device keeps us from touching an ifb0 someone else may own.
CAKE_IFB_DEVICE = "ifb-lr"
CAKE_MAX_MBIT = 100000
CAKE_TC_PATH = "/usr/sbin/tc"

_BANDWIDTH_RE = re.compile(r"bandwidth\s+(\d+)([KMGT]?)bit", re.IGNORECASE)


def normalize_bandwidth(value: Any, *, required: bool, label: str) -> tuple[int, str | None]:
    """Parse a Mbit/s figure into an int; 0 means "do not shape this direction"."""
    raw = str(value or "").strip()
    if not raw:
        if required:
            return 0, f"{label}不能为空"
        return 0, None
    if not raw.isdigit():
        return 0, f"{label}必须是整数（单位 Mbit/s）"
    number = int(raw)
    if number <= 0:
        if required:
            return 0, f"{label}必须大于 0"
        return 0, None
    if number > CAKE_MAX_MBIT:
        return 0, f"{label}不能超过 {CAKE_MAX_MBIT} Mbit/s"
    return number, None


def cake_enabled(config: dict[str, Any]) -> bool:
    return bool(config.get("cake_enabled")) and int(config.get("cake_upload_mbit") or 0) > 0


