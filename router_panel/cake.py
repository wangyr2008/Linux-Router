def render_cake_script(config: dict[str, Any]) -> str:
    """Shell script that (re)attaches CAKE, or clears it when disabled.

    `ensure` mode is a no-op when the qdisc already matches, so the timer can run
    it repeatedly without resetting statistics.
    """
    wan = str(config.get("wan_interface", "") or "")
    upload = int(config.get("cake_upload_mbit") or 0) if cake_enabled(config) else 0
    download = int(config.get("cake_download_mbit") or 0) if cake_enabled(config) else 0
    return "\n".join(
        [
            "#!/bin/sh",
            "# Generated by Linux Router - CAKE traffic shaping. Do not edit by hand.",
            f'WAN="{wan}"',
            f'UPLOAD="{upload}"',
            f'DOWNLOAD="{download}"',
            f'IFB="{CAKE_IFB_DEVICE}"',
            f'TC="{CAKE_TC_PATH}"',
            "",
            "clear_all() {",
            '  [ -n "$WAN" ] || return 0',
            '  "$TC" qdisc del dev "$WAN" root 2>/dev/null || true',
            '  "$TC" qdisc del dev "$WAN" ingress 2>/dev/null || true',
            '  "$TC" qdisc del dev "$IFB" root 2>/dev/null || true',
            '  ip link del "$IFB" 2>/dev/null || true',
            "}",
            "",
            "current_bandwidth() {",
            '  "$TC" qdisc show dev "$1" 2>/dev/null | head -n 1',
            "}",
            "",
            "apply() {",
            '  [ -n "$WAN" ] || return 0',
            '  [ "$UPLOAD" -gt 0 ] || return 0',
            '  "$TC" qdisc replace dev "$WAN" root cake bandwidth "${UPLOAD}mbit" || return 1',
            '  if [ "$DOWNLOAD" -gt 0 ]; then',
            '    ip link show "$IFB" >/dev/null 2>&1 || ip link add "$IFB" type ifb || return 1',
            '    ip link set "$IFB" up || return 1',
            (
                '    "$TC" qdisc replace dev "$WAN" handle ffff: ingress 2>/dev/null'
                ' || "$TC" qdisc add dev "$WAN" handle ffff: ingress || return 1'
            ),
            (
                '    "$TC" filter replace dev "$WAN" parent ffff: protocol all u32'
                ' match u32 0 0 action mirred egress redirect dev "$IFB" || return 1'
            ),
            '    "$TC" qdisc replace dev "$IFB" root cake bandwidth "${DOWNLOAD}mbit" || return 1',
            "  fi",
            "  return 0",
            "}",
            "",
            "ensure() {",
            '  [ -n "$WAN" ] || return 0',
            '  [ "$UPLOAD" -gt 0 ] || { clear_all; return 0; }',
            '  case "$(current_bandwidth "$WAN")" in',
            "    *cake*)",
            '      if [ "$DOWNLOAD" -gt 0 ]; then',
            '        case "$(current_bandwidth "$IFB")" in',
            "          *cake*) return 0 ;;",
            "        esac",
            "      else",
            "        return 0",
            "      fi",
            "      ;;",
            "  esac",
            "  clear_all",
            "  apply",
            "}",
            "",
            'case "${1:-apply}" in',
            "  clear) clear_all ;;",
            "  ensure) ensure ;;",
            "  *) clear_all; apply ;;",
            "esac",
            "",
        ]
    )


def render_service_unit() -> str:
    return "\n".join(
        [
            "[Unit]",
            "Description=Linux Router CAKE traffic shaping",
            "Documentation=man:tc-cake(8)",
            "After=network-online.target",
            "Wants=network-online.target",
            "",
            "[Service]",
            "Type=oneshot",
            "RemainAfterExit=yes",
            f"ExecStart=/bin/sh {CAKE_SCRIPT_PATH} apply",
            f"ExecStop=/bin/sh {CAKE_SCRIPT_PATH} clear",
            "",
            "[Install]",
            "WantedBy=multi-user.target",
            "",
        ]
    )


def render_timer_unit() -> str:
    """Re-attach the qdisc after a PPPoE redial recreates the WAN device."""
    return "\n".join(
        [
            "[Unit]",
            "Description=Linux Router CAKE traffic shaping watchdog",
            "",
            "[Timer]",
            "OnBootSec=90",
            "OnUnitActiveSec=5min",
            "AccuracySec=30s",
            "",
            "[Install]",
            "WantedBy=timers.target",
            "",
        ]
    )


