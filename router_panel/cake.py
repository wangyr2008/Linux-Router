def apply_cake(config: dict[str, Any]) -> CommandResult:
    """Write the script and units, then (re)apply the qdisc."""
    if not command_exists("tc"):
        return CommandResult(False, "系统缺少 tc 命令，请安装 iproute2")

    try:
        atomic_write_text(CAKE_SCRIPT_PATH, render_cake_script(config), mode=0o755)
        atomic_write_text(CAKE_SERVICE_PATH, render_service_unit(), mode=0o644)
        atomic_write_text(CAKE_TIMER_PATH, render_timer_unit(), mode=0o644)
    except OSError as exc:
        return CommandResult(False, f"写入 CAKE 配置失败：{exc}")

    run_command(["systemctl", "daemon-reload"], timeout=SYSTEM_COMMAND_TIMEOUT)
    enabled = run_command(["systemctl", "enable", CAKE_SERVICE_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)
    if not enabled.ok:
        return CommandResult(False, f"启用 {CAKE_SERVICE_NAME} 失败：{enabled.output or '未知错误'}")

    if not cake_enabled(config):
        run_command(["systemctl", "disable", "--now", CAKE_TIMER_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)
        run_command(["systemctl", "stop", CAKE_SERVICE_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)
        cleared = run_command(["/bin/sh", str(CAKE_SCRIPT_PATH), "clear"], timeout=SYSTEM_COMMAND_TIMEOUT)
        if not cleared.ok:
            return CommandResult(False, f"清除 CAKE 规则失败：{cleared.output or '未知错误'}")
        return CommandResult(True, "CAKE 限速已关闭")

    started = run_command(["systemctl", "restart", CAKE_SERVICE_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)
    if not started.ok:
        return CommandResult(False, f"应用 CAKE 规则失败：{started.output or '未知错误'}")
    run_command(["systemctl", "enable", "--now", CAKE_TIMER_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)

    wan = str(config.get("wan_interface", "") or "")
    upload = int(config.get("cake_upload_mbit") or 0)
    download = int(config.get("cake_download_mbit") or 0)
    detail = f"CAKE 已生效：{wan} 上行 {upload} Mbit/s"
    if download > 0:
        detail += f"，下行 {download} Mbit/s"
    return CommandResult(True, detail)


def _parse_bandwidth(line: str) -> int:
    match = _BANDWIDTH_RE.search(line or "")
    if not match:
        return 0
    value = int(match.group(1))
    unit = match.group(2).upper()
    if unit == "K":
        return max(1, value // 1000)
    if unit == "G":
        return value * 1000
    if unit == "T":
        return value * 1000000
    return value


def get_cake_status(config: dict[str, Any]) -> dict[str, Any]:
    wan = str(config.get("wan_interface", "") or "")
    status: dict[str, Any] = {
        "enabled": cake_enabled(config),
        "wan": wan,
        "upload_mbit": int(config.get("cake_upload_mbit") or 0),
        "download_mbit": int(config.get("cake_download_mbit") or 0),
        "available": command_exists("tc"),
        "service_active": is_service_active(CAKE_SERVICE_NAME),
        "active": False,
        "wan_qdisc": "",
        "ifb_qdisc": "",
        "wan_bandwidth": 0,
        "download_bandwidth": 0,
        "errors": [],
    }
    if not status["available"]:
        status["errors"].append("系统未安装 iproute2（缺少 tc）")
        return status
    if not wan:
        return status

    wan_line = (run_command(["tc", "qdisc", "show", "dev", wan], timeout=8).output or "").strip()
    status["wan_qdisc"] = wan_line.splitlines()[0].strip() if wan_line else ""
    if "cake" in status["wan_qdisc"]:
        status["wan_bandwidth"] = _parse_bandwidth(status["wan_qdisc"])

    ifb_line = (
        run_command(["tc", "qdisc", "show", "dev", CAKE_IFB_DEVICE], timeout=8).output or ""
    ).strip()
    status["ifb_qdisc"] = ifb_line.splitlines()[0].strip() if ifb_line else ""
    if "cake" in status["ifb_qdisc"]:
        status["download_bandwidth"] = _parse_bandwidth(status["ifb_qdisc"])

    status["active"] = "cake" in status["wan_qdisc"]
    return status


