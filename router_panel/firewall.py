NFTABLES_INCLUDE_LINE = 'include "/etc/nftables.d/*.nft"'
# No `flush ruleset` on purpose: see ensure_nftables_include().
NFTABLES_CONF_TEMPLATE = (
    "#!/usr/sbin/nft -f\n"
    "\n"
    "# Linux Router: rules live in /etc/nftables.d/*.nft.\n"
    "# No global flush here on purpose - Docker, Podman, Tailscale and WireGuard\n"
    "# keep their own tables, and a ruleset-wide flush deletes them.\n"
    f"{NFTABLES_INCLUDE_LINE}\n"
)
# Debian's unit stops with `nft flush ruleset`; that also nukes foreign tables.
NFTABLES_DROPIN_DIR = Path("/etc/systemd/system/nftables.service.d")
NFTABLES_DROPIN_PATH = NFTABLES_DROPIN_DIR / "10-linux-router.conf"
NFTABLES_DROPIN = (
    "# Generated by Linux Router - keep other tables alive on stop/restart.\n"
    "[Service]\n"
    "ExecStop=\n"
)
NFTABLES_SERVICE = "nftables.service"
FIREWALL_TABLE_FORWARD = "inet lr_forward"
FIREWALL_TABLE_NAT4 = "ip lr_nat"
FIREWALL_TABLE_NAT6 = "ip6 lr_nat6"
FIREWALL_TABLE_INPUT = "inet lr_input"
FIREWALL_MODE_OPEN = "open"
FIREWALL_MODE_PROTECT = "protect"
FIREWALL_MODES = (FIREWALL_MODE_OPEN, FIREWALL_MODE_PROTECT)
FIREWALL_MODE_LABELS = {
    FIREWALL_MODE_OPEN: "开放（只做 NAT，不拦截入站）",
    FIREWALL_MODE_PROTECT: "保护（默认拒绝入站，只放行本机服务）",
}
# Ports the router itself must answer on the LAN.
LAN_BASE_TCP_PORTS = ("22", "53", "80")
LAN_BASE_UDP_PORTS = ("53", "67", "547")
# DHCPv4 client (68) and DHCPv6 client (546) replies arrive on the WAN.
WAN_BASE_UDP_PORTS = ("68", "546")
TAILSCALE_INTERFACE = "tailscale0"

_PORT_ITEM_RE = re.compile(r"^\d{1,5}(?:-\d{1,5})?$")
_NAT_COUNTER_RE = re.compile(r"counter packets (\d+) bytes (\d+)")


def _quote(value: str) -> str:
    return '"' + value.replace('"', "") + '"'


def parse_port_list(raw: Any) -> tuple[list[str], str | None]:
    """Normalise "22, 80, 1000-2000" into a validated list."""
    if raw is None:
        return [], None
    if isinstance(raw, (list, tuple)):
        items = [str(item).strip() for item in raw]
    else:
        items = [part.strip() for part in re.split(r"[\s,;]+", str(raw)) if part.strip()]

    ports: list[str] = []
    for item in items:
        if not item:
            continue
        if not _PORT_ITEM_RE.fullmatch(item):
            return [], f"端口格式无效：{item}（只支持 80 或 1000-2000 这种写法）"
        if "-" in item:
            start, end = item.split("-", 1)
            if not (1 <= int(start) <= 65535 and 1 <= int(end) <= 65535):
                return [], f"端口超出范围：{item}"
            if int(start) > int(end):
                return [], f"端口范围起止颠倒：{item}"
        elif not 1 <= int(item) <= 65535:
            return [], f"端口超出范围：{item}"
        if item not in ports:
            ports.append(item)
    return ports, None


def _port_set(ports: list[str]) -> str:
    return "{ " + ", ".join(ports) + " }"


def _merge(*groups: Any) -> list[str]:
    merged: list[str] = []
    for group in groups:
        for item in group:
            if item not in merged:
                merged.append(item)
    return merged


def render_nftables_ruleset(config: dict[str, Any]) -> str:
    """Build the nftables ruleset for the router.

    Always: forwarding + NAT. In protect mode it additionally adds an input chain
    (policy drop) and tightens forwarding, which is what keeps a LAN behind a
    delegated public IPv6 prefix from being reachable from the outside.
    """
    wan = str(config.get("wan_interface", "") or "").strip()
    lan = str(config.get("lan_interface", "") or "").strip()
    lan_network = str(config.get("lan_network", "") or "").strip()
    # ``ipv6_lan_network`` is the resolved LAN prefix; ``ipv6_prefix`` is the raw setting.
    ipv6_lan_network = str(
        config.get("ipv6_lan_network") or config.get("ipv6_prefix") or ""
    ).strip()
    ipv6_nat = bool(config.get("ipv6_nat", False))
    if str(config.get("ipv6_mode", "")) == "off":
        ipv6_lan_network = ""

    mode = str(config.get("firewall_mode", FIREWALL_MODE_OPEN))
    protect = mode == FIREWALL_MODE_PROTECT
    lan_tcp, _ = parse_port_list(config.get("firewall_lan_tcp"))
    wan_tcp, _ = parse_port_list(config.get("firewall_wan_tcp"))
    wan_udp, _ = parse_port_list(config.get("firewall_wan_udp"))

    lines: list[str] = [
        "#!/usr/sbin/nft -f",
        "# Generated by Linux Router - do not edit by hand.",
        "# Reload with: systemctl reload nftables.service",
        "",
        "# Re-create our own tables on every load, leave other tables alone.",
        f"table {FIREWALL_TABLE_FORWARD}",
        f"delete table {FIREWALL_TABLE_FORWARD}",
        f"table {FIREWALL_TABLE_NAT4}",
        f"delete table {FIREWALL_TABLE_NAT4}",
        f"table {FIREWALL_TABLE_NAT6}",
        f"delete table {FIREWALL_TABLE_NAT6}",
        f"table {FIREWALL_TABLE_INPUT}",
        f"delete table {FIREWALL_TABLE_INPUT}",
        "",
        f"table {FIREWALL_TABLE_FORWARD} {{",
        "    chain forward {",
        f"        type filter hook forward priority filter; policy {'drop' if protect else 'accept'};",
        "        ct state established,related accept",
        "        ct state invalid drop",
    ]

    if protect:
        if lan:
            lines.append(f"        iifname {_quote(lan)} accept")
        lines.append(f"        iifname {_quote(TAILSCALE_INTERFACE)} accept")
        lines.append("        # Everything else (new inbound connections from the WAN) is dropped.")
    elif lan and wan:
        lines.extend(
            [
                f"        iifname {_quote(lan)} oifname {_quote(wan)} accept",
                f"        iifname {_quote(wan)} oifname {_quote(lan)} accept",
                f"        iifname {_quote(lan)} oifname {_quote(lan)} accept",
            ]
        )
        lines.append("        # policy accept keeps the router transparent; switch to 保护 to filter.")
    lines.extend(["    }", "}", ""])

    if wan and lan_network:
        lines.extend(
            [
                f"table {FIREWALL_TABLE_NAT4} {{",
                "    chain postrouting {",
                "        type nat hook postrouting priority srcnat; policy accept;",
                f"        ip saddr {lan_network} oifname {_quote(wan)} counter masquerade",
                "    }",
                "}",
                "",
            ]
        )

    if wan and ipv6_lan_network and ipv6_nat:
        lines.extend(
            [
                f"table {FIREWALL_TABLE_NAT6} {{",
                "    chain postrouting {",
                "        type nat hook postrouting priority srcnat; policy accept;",
                f"        ip6 saddr {ipv6_lan_network} oifname {_quote(wan)} counter masquerade",
                "    }",
                "}",
                "",
            ]
        )

    if protect and lan:
        lines.extend(_render_input_chain(lan, wan, lan_tcp, wan_tcp, wan_udp))

    return "\n".join(lines)


def _render_input_chain(
    lan: str,
    wan: str,
    lan_tcp: list[str],
    wan_tcp: list[str],
    wan_udp: list[str],
) -> list[str]:
    lines = [
        f"table {FIREWALL_TABLE_INPUT} {{",
        "    chain input {",
        "        type filter hook input priority filter; policy drop;",
        "        ct state established,related accept",
        "        ct state invalid drop",
        '        iifname "lo" accept',
        "",
        "        # ICMP/ICMPv6 is required for PMTU and neighbour discovery.",
        "        meta l4proto icmp accept",
        "        meta l4proto ipv6-icmp accept",
        "",
        f"        iifname {_quote(TAILSCALE_INTERFACE)} accept",
    ]

    if wan:
        lines.append("")
        lines.append("        # DHCP client replies on the WAN")
        lines.append(f"        iifname {_quote(wan)} udp dport {_port_set(_merge(WAN_BASE_UDP_PORTS, wan_udp))} accept")
        if wan_tcp:
            lines.append(f"        iifname {_quote(wan)} tcp dport {_port_set(wan_tcp)} accept")

    lines.append("")
    lines.append("        # Router services reachable from the LAN")
    lines.append(
        f"        iifname {_quote(lan)} tcp dport {_port_set(_merge(LAN_BASE_TCP_PORTS, lan_tcp))} accept"
    )
    lines.append(f"        iifname {_quote(lan)} udp dport {_port_set(list(LAN_BASE_UDP_PORTS))} accept")
    lines.extend(["    }", "}", ""])
    return lines


def nftables_config_includes_our_ruleset() -> bool:
    content = read_text(str(NFTABLES_CONFIG_PATH))
    if not content:
        return False
    for raw_line in content.splitlines():
        line = raw_line.split("#", 1)[0].strip()
        if line == NFTABLES_INCLUDE_LINE:
            return True
        if line.startswith("include") and "nftables.d" in line:
            return True
    return False


def ensure_nftables_include() -> CommandResult:
    """Make /etc/nftables.conf pull in /etc/nftables.d/*.nft, without a global flush.

    Debian ships `flush ruleset` plus an empty `table inet filter` in this file,
    and `systemctl reload nftables` re-runs it. A global flush deletes every
    table on the box — Docker's `ip nat`/`ip filter`, Podman's, Tailscale's
    `inet tailscale`, WireGuard's PostUp rules — and none of them come back
    until the owning service is restarted. Our own ruleset already recreates its
    lr_* tables on load, so the flush buys nothing.
    """
    try:
        NFTABLES_CONF_DIR.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        return CommandResult(False, f"创建 {NFTABLES_CONF_DIR} 失败：{exc}")
    dropin_note = _ensure_nftables_stop_override()
    if nftables_config_includes_our_ruleset() and not _nftables_conf_flushes():
        return CommandResult(True, f"nftables.conf 已包含 /etc/nftables.d 且不会 flush 其它表{dropin_note}")

    existing = read_text(str(NFTABLES_CONFIG_PATH))
    backup = NFTABLES_CONFIG_PATH.with_name(NFTABLES_CONFIG_PATH.name + ".linux-router.bak")
    if existing:
        # Keep whatever was there (possibly hand-written rules) next to the file.
        try:
            if not backup.exists():
                atomic_write_text(backup, existing, mode=0o600)
        except OSError as exc:
            return CommandResult(False, f"备份 {NFTABLES_CONFIG_PATH} 失败：{exc}")

    try:
        atomic_write_text(NFTABLES_CONFIG_PATH, NFTABLES_CONF_TEMPLATE, mode=0o755)
    except OSError as exc:
        return CommandResult(False, f"写入 {NFTABLES_CONFIG_PATH} 失败：{exc}")
    if not existing:
        return CommandResult(True, f"已创建 /etc/nftables.conf 并引入 /etc/nftables.d{dropin_note}")
    return CommandResult(
        True,
        f"已重写 /etc/nftables.conf：不再 flush 整个 ruleset，原文件备份为 {backup.name}{dropin_note}",
    )


def _ensure_nftables_stop_override() -> str:
    """Drop Debian's `ExecStop=nft flush ruleset` via a unit drop-in.

    `systemctl restart nftables` runs ExecStop first, so without this a restart
    still wipes Docker/Tailscale tables even though our conf no longer flushes.
    """
    current = read_text(str(NFTABLES_DROPIN_PATH))
    if current == NFTABLES_DROPIN:
        return ""
    try:
        NFTABLES_DROPIN_DIR.mkdir(parents=True, exist_ok=True)
        atomic_write_text(NFTABLES_DROPIN_PATH, NFTABLES_DROPIN, mode=0o644)
    except OSError as exc:
        return f"（写入 nftables drop-in 失败：{exc}）"
    run_command(["systemctl", "daemon-reload"], timeout=SYSTEM_COMMAND_TIMEOUT)
    return "，并取消 nftables.service 停止时的 flush"


def _nftables_conf_flushes() -> bool:
    content = read_text(str(NFTABLES_CONFIG_PATH))
    for raw_line in content.splitlines():
        if raw_line.split("#", 1)[0].strip() == "flush ruleset":
            return True
    return False


def check_ruleset(ruleset: str) -> CommandResult:
    if not command_exists("nft"):
        return CommandResult(False, "系统缺少 nft 命令，请安装 nftables")
    NFTABLES_CONF_DIR.mkdir(parents=True, exist_ok=True)
    probe = NFTABLES_CONF_DIR / ".linux-router-check.nft"
    try:
        atomic_write_text(probe, ruleset, mode=0o600)
        return run_command(["nft", "-c", "-f", str(probe)], timeout=15)
    finally:
        try:
            probe.unlink()
        except OSError:
            pass


def reset_router_tables() -> None:
    """Drop our tables so a broken ruleset can be reloaded from scratch."""
    for table in (
        FIREWALL_TABLE_FORWARD,
        FIREWALL_TABLE_NAT4,
        FIREWALL_TABLE_NAT6,
        FIREWALL_TABLE_INPUT,
    ):
        run_command(["nft", "delete", "table", table], timeout=10)


def apply_ruleset(ruleset: str) -> CommandResult:
    checked = check_ruleset(ruleset)
    if not checked.ok:
        return CommandResult(False, f"nftables 规则校验失败：{checked.output or '未知错误'}")

    include = ensure_nftables_include()
    if not include.ok:
        return include

    try:
        atomic_write_text(NFTABLES_RULESET_PATH, ruleset, mode=0o644)
    except OSError as exc:
        return CommandResult(False, f"写入 {NFTABLES_RULESET_PATH} 失败：{exc}")

    applied = run_command(["nft", "-f", str(NFTABLES_RULESET_PATH)], timeout=20)
    if not applied.ok:
        # The ruleset recreates its own tables, but a table left behind by an older
        # layout would abort the load. Reset once and retry before giving up.
        reset_router_tables()
        applied = run_command(["nft", "-f", str(NFTABLES_RULESET_PATH)], timeout=20)
    if not applied.ok:
        return CommandResult(False, f"加载 nftables 规则失败：{applied.output or '未知错误'}")

    run_command(["systemctl", "enable", NFTABLES_SERVICE], timeout=20)
    if is_service_active(NFTABLES_SERVICE):
        # nftables.service re-reads /etc/nftables.conf, which includes our file.
        reloaded = run_command(["systemctl", "reload", NFTABLES_SERVICE], timeout=20)
        if not reloaded.ok:
            return CommandResult(True, "规则已生效，但 nftables.service reload 失败，重启后请复查")
    else:
        run_command(["systemctl", "start", NFTABLES_SERVICE], timeout=20)
    return CommandResult(True, "nftables 规则已生效")


def _table_exists(table: str) -> bool:
    return run_command(["nft", "list", "table", table], timeout=8).ok


def _chain_counters(table: str) -> int:
    result = run_command(["nft", "list", "chain", table, "postrouting"], timeout=8)
    if not result.ok or not result.output:
        return 0
    match = _NAT_COUNTER_RE.search(result.output)
    return int(match.group(1)) if match else 0


def get_firewall_status() -> dict[str, Any]:
    available = command_exists("nft")
    status: dict[str, Any] = {
        "available": available,
        "service_active": is_service_active(NFTABLES_SERVICE),
        "service_enabled": is_service_enabled(NFTABLES_SERVICE),
        "ruleset_path": str(NFTABLES_RULESET_PATH),
        "ruleset_present": NFTABLES_RULESET_PATH.exists(),
        "include_present": nftables_config_includes_our_ruleset(),
        "forward_table": False,
        "input_table": False,
        "nat4": False,
        "nat6": False,
        "nat4_packets": 0,
        "nat6_packets": 0,
        "errors": [],
    }
    if not available:
        status["errors"].append("系统未安装 nftables")
        return status

    status["forward_table"] = _table_exists(FIREWALL_TABLE_FORWARD)
    status["input_table"] = _table_exists(FIREWALL_TABLE_INPUT)
    status["nat4"] = _table_exists(FIREWALL_TABLE_NAT4)
    status["nat6"] = _table_exists(FIREWALL_TABLE_NAT6)
    if status["nat4"]:
        status["nat4_packets"] = _chain_counters(FIREWALL_TABLE_NAT4)
    if status["nat6"]:
        status["nat6_packets"] = _chain_counters(FIREWALL_TABLE_NAT6)
    return status


