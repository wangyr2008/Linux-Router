def render_ppp_network() -> str:
    """ppp0 is created by pppd; networkd only runs the DHCPv6 client on it.

    A PPP link never sends Router Advertisements, so DHCPv6 has to start without
    waiting for one (`WithoutRA=solicit`), otherwise prefix delegation never runs.
    """
    return "\n".join(
        [
            "# Generated by Linux Router - PPPoE uplink (ppp0).",
            "[Match]",
            f"Name={PPPOE_INTERFACE}",
            "",
            "[Network]",
            "DHCP=ipv6",
            "IPv6AcceptRA=no",
            "",
            "[DHCPv6]",
            "WithoutRA=solicit",
            "UseDNS=yes",
            "",
        ]
    )


def render_pppoe_peers(config: dict[str, Any]) -> str:
    nic = str(config.get("pppoe_nic", "") or "")
    mtu = str(config.get("mtu", "") or "").strip() or "1492"
    return "\n".join(
        [
            "# Generated by Linux Router - PPPoE session options.",
            "plugin rp-pppoe.so",
            f"nic-{nic}",
            f'user "{config.get("pppoe_username", "")}"',
            "noauth",
            "hide-password",
            "noipdefault",
            "defaultroute",
            "replacedefaultroute",
            "persist",
            "maxfail 0",
            "holdoff 10",
            "lcp-echo-interval 20",
            "lcp-echo-failure 3",
            f"mtu {mtu}",
            f"mru {mtu}",
            "ipv6 ,",
            "",
        ]
    )


def render_pppoe_secrets(config: dict[str, Any]) -> str:
    username = str(config.get("pppoe_username", "") or "")
    password = str(config.get("pppoe_password", "") or "")
    return f'"{username}" * "{password}" *\n'


def render_ppp_ipup_script() -> str:
    """Restore what a redial breaks, without waiting for the 5-minute timers.

    A new session recreates ppp0 (the CAKE qdisc is gone with it) and the ISP may
    hand out a different DNS server, so both are refreshed immediately.
    """
    return "\n".join(
        [
            "#!/bin/sh",
            "# Generated by Linux Router - runs after the PPP link comes up.",
            "if [ -x /etc/linux-router/cake.sh ]; then",
            "  /bin/sh /etc/linux-router/cake.sh ensure >/dev/null 2>&1 || true",
            "fi",
            "systemctl start linux-router-dns.service >/dev/null 2>&1 || true",
            "exit 0",
            "",
        ]
    )


