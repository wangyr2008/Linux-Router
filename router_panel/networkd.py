def _ip_json(*args: str) -> list[dict[str, Any]]:
    result = run_command(["ip", "-j", *args], timeout=8)
    if not result.ok or not result.output:
        return []
    try:
        payload = json.loads(result.output)
    except json.JSONDecodeError:
        return []
    return payload if isinstance(payload, list) else []


def get_configured_methods() -> dict[str, tuple[str, str]]:
    """Map interface -> (ipv4 method, ipv6 method) from our own .network files."""
    methods: dict[str, tuple[str, str]] = {}
    try:
        entries = sorted(NETWORKD_DIR.glob("*.network"))
    except OSError:
        return methods
    for path in entries:
        try:
            content = path.read_text(encoding="utf-8")
        except OSError:
            continue
        name = ""
        dhcp = ""
        has_address = False
        accepts_ra = True
        for raw in content.splitlines():
            line = raw.split("#", 1)[0].strip()
            if line.startswith("Name=") and not name:
                name = line.split("=", 1)[1].strip()
            elif line.startswith("DHCP="):
                dhcp = line.split("=", 1)[1].strip().lower()
            elif line.startswith("Address="):
                has_address = True
            elif line.startswith("IPv6AcceptRA="):
                accepts_ra = line.split("=", 1)[1].strip().lower() in {"yes", "true", "1"}
        if not name:
            continue
        if dhcp in {"yes", "ipv4", "both"}:
            ipv4_method = "auto"
        elif has_address:
            ipv4_method = "manual"
        else:
            ipv4_method = "disabled"
        if dhcp in {"yes", "ipv6", "both"}:
            ipv6_method = "auto"
        elif accepts_ra:
            ipv6_method = "auto"
        else:
            ipv6_method = "manual" if has_address else "disabled"
        methods[name] = (ipv4_method, ipv6_method)
    return methods


def get_link_status() -> dict[str, dict[str, Any]]:
    """operstate + addresses for every non-loopback link."""
    status: dict[str, dict[str, Any]] = {}
    for interface in _ip_json("address", "show"):
        ifname = str(interface.get("ifname", "") or "")
        if not ifname or ifname == "lo":
            continue
        ipv4: list[str] = []
        ipv6: list[str] = []
        for address in interface.get("addr_info", []):
            local = str(address.get("local", "") or "")
            if not local or address.get("scope") == "host":
                continue
            prefixlen = address.get("prefixlen")
            formatted = f"{local}/{prefixlen}" if prefixlen is not None else local
            if address.get("family") == "inet":
                ipv4.append(formatted)
            elif address.get("family") == "inet6" and not local.lower().startswith("fe80:"):
                ipv6.append(formatted)
        status[ifname] = {
            "name": ifname,
            "operstate": str(interface.get("operstate", "") or "").lower(),
            "ipv4": ipv4,
            "ipv6": ipv6,
            "mac": str(interface.get("address", "") or ""),
            "kind": str(interface.get("link_type", "") or ""),
        }
    return status


def get_link_dns(ifname: str) -> list[str]:
    """DNS servers networkd learned for one link.

    ``/run/systemd/netif/links/<ifindex>`` carries a locale-independent ``DNS=``
    line, which is far more reliable to read than parsing `networkctl status`.
    """
    if not ifname:
        return []
    try:
        index = (SYS_CLASS_NET / ifname / "ifindex").read_text(encoding="utf-8").strip()
    except OSError:
        return []
    try:
        content = (NETIF_LINKS_DIR / index).read_text(encoding="utf-8")
    except OSError:
        return []

    servers: list[str] = []
    for line in content.splitlines():
        if not line.startswith("DNS="):
            continue
        for value in line.split("=", 1)[1].split():
            if value and value not in servers:
                servers.append(value)
    return servers


def resolve_upstream_dns(config: dict[str, Any]) -> list[str]:
    """Configured upstream DNS wins; otherwise use what the WAN link learned."""
    configured = str(config.get("dns_upstream", "") or "").split()
    if configured:
        return configured
    return get_link_dns(str(config.get("wan_interface", "") or ""))


def write_resolv_conf(config: dict[str, Any], retries: int = 0) -> CommandResult:
    """Keep the router's own resolver pointed at the uplink DNS.

    networkd does not write /etc/resolv.conf without systemd-resolved, and a
    minimal Debian install does not ship it, so the panel maintains the file
    itself. An empty result leaves the existing file untouched instead of
    wiping DNS entirely.
    """
    servers: list[str] = []
    for attempt in range(retries + 1):
        servers = resolve_upstream_dns(config)
        if servers or attempt == retries:
            break
        # Right after a networkd restart the per-link file is not written yet.
        time.sleep(1)
    if not servers:
        return CommandResult(True, "未获取到 WAN DNS，保留现有 /etc/resolv.conf")

    content = ["# Generated by Linux Router - upstream DNS from the WAN link."]
    content.extend(f"nameserver {server}" for server in servers)
    try:
        atomic_write_text(RESOLV_CONF_PATH, "\n".join(content) + "\n", mode=0o644)
    except OSError as exc:
        return CommandResult(False, f"写入 /etc/resolv.conf 失败：{exc}")
    return CommandResult(True, f"上游 DNS：{', '.join(servers)}")


