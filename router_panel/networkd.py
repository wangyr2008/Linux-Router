def render_wan_network(config: dict[str, Any]) -> str:
    """WAN .network for a DHCP uplink (PPPoE has no ethernet uplink to configure)."""
    wan = str(config.get("wan_interface", "") or "")
    lines = ["# Generated by Linux Router - WAN uplink.", "[Match]", f"Name={wan}", ""]
    mtu = str(config.get("mtu", "") or "").strip()
    if mtu:
        lines.extend(["[Link]", f"MTUBytes={mtu}", ""])
    lines.append("[Network]")
    if config.get("wan_ipv6_auto"):
        lines.append("DHCP=yes")
        lines.append("IPv6AcceptRA=yes")
    else:
        lines.append("DHCP=ipv4")
        lines.append("IPv6AcceptRA=no")
    lines.extend(
        [
            "",
            "[DHCPv4]",
            "UseDomains=no",
            "RouteMetric=100",
            "",
            "[DHCPv6]",
            "UseDNS=yes",
            "",
        ]
    )
    return "\n".join(lines)


def _lan_ipv6_lines(config: dict[str, Any]) -> list[str]:
    from .routing import IPV6_MODE_OFF, IPV6_MODE_PD, lan_ipv6_address, lan_ipv6_network

    mode = str(config.get("ipv6_mode", "") or "")
    if mode == IPV6_MODE_OFF:
        return []
    if mode == IPV6_MODE_PD:
        # The address comes from the delegated prefix at runtime.
        return []
    network = lan_ipv6_network(config)
    address = lan_ipv6_address(config)
    if network is None or address is None:
        return []
    return [f"Address={address}/{network.prefixlen}"]


def render_lan_network(config: dict[str, Any]) -> str:
    """LAN .network: static IPv4, IPv6 addressing, and Router Advertisements.

    networkd owns IPv6 (address + RA + RDNSS) so a delegated prefix can be
    announced without a second RA source; dnsmasq keeps doing DHCPv4 and DNS.
    The LAN always gets fe80::1 so RDNSS can advertise a stable DNS address even
    when the global prefix is only known at runtime (PD).
    """
    from .routing import IPV6_MODE_OFF, IPV6_MODE_PD, _lan_ipv4_network, lan_gateway_ipv4

    lan = str(config.get("lan_interface", "") or "")
    network = _lan_ipv4_network(config)
    gateway = lan_gateway_ipv4(config)
    mode = str(config.get("ipv6_mode", "") or "")

    lines = [
        "# Generated by Linux Router - LAN.",
        "[Match]",
        f"Name={lan}",
        "",
        "[Network]",
        f"Address={gateway}/{network.prefixlen}",
        "ConfigureWithoutCarrier=no",
        "IPForward=yes",
    ]
    lines.extend(_lan_ipv6_lines(config))

    if mode != IPV6_MODE_OFF:
        lines.extend(["Address=fe80::1/64", "DNS=fe80::1", "IPv6SendRA=yes"])
        if mode == IPV6_MODE_PD:
            # Ask the DHCPv6 client on the WAN link for prefixes for this link.
            lines.extend(["DHCPPrefixDelegation=yes", "IPv6AcceptRA=no"])

    lines.append("")
    if mode != IPV6_MODE_OFF:
        lines.extend(
            [
                "[IPv6SendRA]",
                "Managed=no",
                "OtherInformation=yes",
                "EmitDNS=yes",
                "EmitDomains=no",
                "",
            ]
        )
    return "\n".join(lines)


