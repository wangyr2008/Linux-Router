def get_dns_servers() -> list[str]:
    servers: list[str] = []
    try:
        content = RESOLV_CONF_PATH.read_text(encoding="utf-8")
    except OSError:
        return servers
    for line in content.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[0] == "nameserver" and parts[1] not in servers:
            servers.append(parts[1])
    return servers


def get_delegated_prefix(lan_interface: str) -> str:
    """The global /64 currently on the LAN (that is what PD produced)."""
    if not lan_interface:
        return ""
    for interface in _ip_json("address", "show", "dev", lan_interface):
        for address in interface.get("addr_info", []):
            local = str(address.get("local", "") or "")
            prefixlen = address.get("prefixlen")
            if address.get("family") != "inet6" or not local:
                continue
            if local.lower().startswith(("fe80:", "fd", "::")):
                continue
            try:
                network = ipaddress.ip_interface(f"{local}/{prefixlen}").network
            except ValueError:
                continue
            if network.prefixlen == 64:
                return str(network)
    return ""


def get_networkd_status(config: dict[str, Any] | None = None) -> dict[str, Any]:
    config = config or {}
    lan = str(config.get("lan_interface", "") or "")
    wan = str(config.get("wan_interface", "") or "")
    links = get_link_status()
    pppoe_active = is_service_active(PPPOE_SERVICE_NAME)
    return {
        "available": command_exists("networkctl"),
        "service": NETWORKD_SERVICE,
        "service_active": is_service_active(NETWORKD_SERVICE),
        "service_enabled": is_service_enabled(NETWORKD_SERVICE),
        "wan_mode": str(config.get("wan_mode", WAN_MODE_DHCP) or WAN_MODE_DHCP),
        "pppoe_service_active": pppoe_active,
        "pppoe_service_enabled": is_service_enabled(PPPOE_SERVICE_NAME),
        "ppp_installed": command_exists("pppd"),
        "wan_link": links.get(wan, {}),
        "lan_link": links.get(lan, {}),
        "delegated": get_delegated_prefix(lan),
        "dns": get_dns_servers(),
        "config_files": [
            str(path.name)
            for path in (WAN_NETWORK_PATH, LAN_NETWORK_PATH, PPP_NETWORK_PATH)
            if path.exists()
        ],
    }


