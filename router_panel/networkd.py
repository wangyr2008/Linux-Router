def _comment_out_ifupdown(interfaces: set[str]) -> list[str]:
    """Stop ifupdown from re-configuring our NICs on the next boot.

    Without this, `ifup` runs before networkd at boot and both stacks fight over
    the same address. A backup is kept next to the original file.
    """
    from .core import IFUPDOWN_INTERFACES_PATH

    notes: list[str] = []
    try:
        content = IFUPDOWN_INTERFACES_PATH.read_text(encoding="utf-8")
    except OSError:
        return notes

    changed = False
    lines: list[str] = []
    for raw in content.splitlines():
        stripped = raw.strip()
        parts = stripped.split()
        target = ""
        if len(parts) >= 2 and parts[0] in {"iface", "allow-hotplug", "auto"}:
            target = parts[1]
        if target and target in interfaces and not stripped.startswith("#"):
            lines.append(f"# {raw}")
            changed = True
        else:
            lines.append(raw)
    if not changed:
        return notes

    try:
        backup = IFUPDOWN_INTERFACES_PATH.with_suffix(".linux-router.bak")
        if not backup.exists():
            backup.write_text(content, encoding="utf-8")
        atomic_write_text(IFUPDOWN_INTERFACES_PATH, "\n".join(lines) + "\n", mode=0o644)
        notes.append("已在 /etc/network/interfaces 中注释掉这些网口")
    except OSError as exc:
        notes.append(f"注释 ifupdown 配置失败：{exc}")
    return notes


def _take_over_interfaces(config: dict[str, Any]) -> list[str]:
    """Retire NetworkManager, dhcpcd and ifupdown for the interfaces we now own."""
    notes: list[str] = []
    for service in ("NetworkManager.service", "dhcpcd.service"):
        if is_service_active(service) or is_service_enabled(service):
            run_command(["systemctl", "disable", "--now", service], timeout=SYSTEM_COMMAND_TIMEOUT)
            notes.append(f"已停止 {service}")

    interfaces = {
        str(config.get(key, "") or "")
        for key in ("wan_interface", "lan_interface", "pppoe_nic")
    }
    interfaces.discard("")
    for ifname in sorted(interfaces):
        unit = f"ifup@{ifname}.service"
        if is_service_active(unit):
            run_command(["systemctl", "stop", unit], timeout=SYSTEM_COMMAND_TIMEOUT)
            notes.append(f"已停止 {unit}")
    notes.extend(_comment_out_ifupdown(interfaces))
    return notes


def _reconfigure(ifname: str) -> CommandResult:
    if not ifname:
        return CommandResult(True, "")
    return run_command(["networkctl", "reconfigure", ifname], timeout=SYSTEM_COMMAND_TIMEOUT)


def apply_networkd(
    config: dict[str, Any],
    progress: ProgressCallback | None = None,
) -> CommandResult:
    def report(message: str) -> None:
        if progress:
            progress(message)

    if not command_exists("networkctl"):
        return CommandResult(False, "系统缺少 networkctl（systemd-networkd），请先安装 systemd")

    wan_mode = str(config.get("wan_mode", WAN_MODE_DHCP) or WAN_MODE_DHCP)
    wan = str(config.get("wan_interface", "") or "")
    lan = str(config.get("lan_interface", "") or "")
    report("写入 systemd-networkd 配置")
    try:
        atomic_write_text(LAN_NETWORK_PATH, render_lan_network(config), mode=0o644)
        if wan_mode == WAN_MODE_PPPOE:
            WAN_NETWORK_PATH.unlink(missing_ok=True)
            atomic_write_text(PPP_NETWORK_PATH, render_ppp_network(), mode=0o644)
            atomic_write_text(PPPOE_PEER_PATH, render_pppoe_peers(config), mode=0o600)
            atomic_write_text(PPPOE_CHAP_PATH, render_pppoe_secrets(config), mode=0o600)
            atomic_write_text(PPPOE_PAP_PATH, render_pppoe_secrets(config), mode=0o600)
            atomic_write_text(PPPOE_SERVICE_PATH, render_pppoe_service(), mode=0o644)
            atomic_write_text(PPPOE_IPUP_PATH, render_ppp_ipup_script(), mode=0o755)
        else:
            PPP_NETWORK_PATH.unlink(missing_ok=True)
            PPPOE_IPUP_PATH.unlink(missing_ok=True)
            atomic_write_text(WAN_NETWORK_PATH, render_wan_network(config), mode=0o644)
    except OSError as exc:
        return CommandResult(False, f"写入网络配置失败：{exc}")

    report("接管网卡")
    notes = _take_over_interfaces(config)

    report("启用 systemd-networkd")
    run_command(["systemctl", "enable", NETWORKD_SERVICE], timeout=SYSTEM_COMMAND_TIMEOUT)
    started = run_command(["systemctl", "restart", NETWORKD_SERVICE], timeout=SYSTEM_COMMAND_TIMEOUT)
    if not started.ok:
        return CommandResult(False, f"启动 systemd-networkd 失败：{started.output or '未知错误'}")

    report("安装 DNS 同步任务")
    try:
        atomic_write_text(DNS_SCRIPT_PATH, render_dns_script(), mode=0o755)
        atomic_write_text(DNS_SERVICE_PATH, render_dns_service(), mode=0o644)
        atomic_write_text(DNS_TIMER_PATH, render_dns_timer(), mode=0o644)
    except OSError as exc:
        return CommandResult(False, f"写入 DNS 同步任务失败：{exc}")

    if wan_mode == WAN_MODE_PPPOE:
        report("启动 PPPoE 拨号")
        run_command(["systemctl", "daemon-reload"], timeout=SYSTEM_COMMAND_TIMEOUT)
        run_command(["systemctl", "enable", PPPOE_SERVICE_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)
        dialed = run_command(["systemctl", "restart", PPPOE_SERVICE_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)
        if not dialed.ok:
            return CommandResult(False, f"启动 PPPoE 拨号失败：{dialed.output or '未知错误'}")
        run_command(["networkctl", "reload"], timeout=SYSTEM_COMMAND_TIMEOUT)
    else:
        report("停用 PPPoE 拨号")
        run_command(["systemctl", "disable", "--now", PPPOE_SERVICE_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)

    report("重新加载链路配置")
    run_command(["networkctl", "reload"], timeout=SYSTEM_COMMAND_TIMEOUT)
    run_command(["systemctl", "daemon-reload"], timeout=SYSTEM_COMMAND_TIMEOUT)
    run_command(["systemctl", "enable", DNS_SERVICE_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)
    run_command(["systemctl", "enable", "--now", DNS_TIMER_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)
    for ifname in (lan, wan):
        if ifname and ifname != PPPOE_INTERFACE:
            _reconfigure(ifname)
    if wan_mode == WAN_MODE_PPPOE:
        _reconfigure(PPPOE_INTERFACE)

    message = f"systemd-networkd 已接管：WAN {wan} → LAN {lan}"
    if notes:
        message += "；" + "，".join(notes)
    return CommandResult(True, message)


def disable_networkd_config() -> None:
    for path in (WAN_NETWORK_PATH, LAN_NETWORK_PATH, PPP_NETWORK_PATH):
        try:
            path.unlink(missing_ok=True)
        except OSError:
            pass
    run_command(["systemctl", "disable", "--now", PPPOE_SERVICE_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)
    for path in (PPPOE_SERVICE_PATH, PPPOE_PEER_PATH):
        try:
            path.unlink(missing_ok=True)
        except OSError:
            pass
    run_command(["systemctl", "daemon-reload"], timeout=SYSTEM_COMMAND_TIMEOUT)
    run_command(["networkctl", "reload"], timeout=SYSTEM_COMMAND_TIMEOUT)


