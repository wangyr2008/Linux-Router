def render_dhcpcd_conf(config: dict[str, Any]) -> str:
    """dhcpcd config that only does IPv6 prefix delegation.

    IPv4 and the WAN IPv6 address stay with NetworkManager, so dhcpcd runs with
    ``noipv4``/``noipv6rs`` and is limited to the WAN + LAN interfaces.
    """
    wan = str(config.get("wan_interface", "") or "")
    lan = str(config.get("lan_interface", "") or "")
    lines = [
        "# Generated by Linux Router - IPv6 prefix delegation only.",
        "# IPv4 and the WAN address are handled by NetworkManager.",
        "noipv4",
        "noipv6rs",
        "duid",
        "persistent",
        "option rapid_commit",
        "option domain_name_servers, domain_name, domain_search, host_name",
        "option classless_static_routes",
        "option interface_mtu",
        "require dhcp_server_identifier",
        "slaac private",
        "# Keep NetworkManager in charge of /etc/resolv.conf and the hostname.",
        "nohook resolv.conf, hostname",
        f"allowinterfaces {wan} {lan}",
        "",
        f"interface {wan}",
        f"  ia_pd 2/::/56 {lan}/{PD_LEASE_SLA_ID}/{PD_SUBNET_PREFIX}",
        "",
        f"interface {lan}",
        "  noipv6rs",
        "",
    ]
    return "\n".join(lines)


def render_hook_script(config: dict[str, Any]) -> str:
    """Hook sourced by dhcpcd-run-hooks; it must never call exit/exec."""
    wan = str(config.get("wan_interface", "") or "")
    reasons = "|".join(PD_SYNC_REASONS)
    return "\n".join(
        [
            "# Linux Router - sync the delegated IPv6 prefix into the LAN.",
            "# Sourced by dhcpcd-run-hooks: keep it side-effect free.",
            f'if [ "$interface" = "{wan}" ]; then',
            '  case "$reason" in',
            f"    {reasons})",
            f'      LINUX_ROUTER_DATA_DIR="{DATA_DIR}" /usr/bin/python3 "{PD_HOOK_ENTRY}" '
            f'"$reason" "$interface" "$new_delegated_dhcp6_prefix" >/dev/null 2>&1',
            "      ;;",
            "  esac",
            "fi",
            "",
        ]
    )


def render_service_unit(config: dict[str, Any]) -> str:
    binary = dhcpcd_binary() or "/usr/sbin/dhcpcd"
    return "\n".join(
        [
            "[Unit]",
            "Description=Linux Router IPv6 prefix delegation (dhcpcd)",
            "Documentation=man:dhcpcd(8)",
            "After=NetworkManager.service network-online.target",
            "Wants=network-online.target",
            "StartLimitIntervalSec=0",
            "",
            "[Service]",
            "Type=simple",
            f"ExecStart={binary} --nobackground --quiet --config {PD_DHCPCD_CONF_PATH}",
            "Restart=always",
            "RestartSec=10",
            "RuntimeDirectory=linux-router-pd",
            "RuntimeDirectoryMode=0750",
            "",
            "[Install]",
            "WantedBy=multi-user.target",
            "",
        ]
    )


