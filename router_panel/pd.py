def _write_dnsmasq_for_prefix(prefix: str) -> CommandResult:
    # Imported lazily: routing imports this module at load time.
    from .core import DNSMASQ_RULESET_PATH
    from .routing import build_dnsmasq_config, ensure_dnsmasq_include, load_router_config

    config = load_router_config()
    config["ipv6_prefix"] = prefix
    include = ensure_dnsmasq_include()
    if not include.ok:
        return include
    try:
        atomic_write_text(DNSMASQ_RULESET_PATH, build_dnsmasq_config(config), mode=0o644)
    except OSError as exc:
        return CommandResult(False, f"写入 dnsmasq 配置失败：{exc}")

    tested = run_command(
        ["dnsmasq", "--test", f"--conf-file={DNSMASQ_RULESET_PATH}"], timeout=15
    )
    if not tested.ok:
        return CommandResult(False, f"dnsmasq 配置校验失败：{tested.output or '未知错误'}")
    restarted = run_command(["systemctl", "restart", "dnsmasq.service"], timeout=SYSTEM_COMMAND_TIMEOUT)
    if not restarted.ok:
        return CommandResult(False, f"重启 dnsmasq 失败：{restarted.output or '未知错误'}")
    return CommandResult(True, f"已按前缀 {prefix or '（无）'} 更新 dnsmasq")


def sync_from_system(delegated_prefix: str = "", reason: str = "") -> int:
    """Called from the dhcpcd hook and right after applying the router config.

    Keeps the LAN /64, the dnsmasq RA range and the state file in sync when the
    ISP renumbers the delegated prefix.
    """
    from .routing import IPV6_MODE_PD, load_router_config

    config = load_router_config()
    if str(config.get("ipv6_mode", "")) != IPV6_MODE_PD:
        return 0

    lan = str(config.get("lan_interface", "") or "")
    if delegated_prefix.strip():
        prefix = derive_lan_prefix(lan, delegated_prefix)
    elif reason in PD_LOSS_REASONS:
        # The delegation is gone; do not resurrect it from a stale interface address.
        prefix = ""
    else:
        prefix = derive_lan_prefix(lan)
    state = load_pd_state()
    previous = str(state.get("prefix", "") or "")

    state.update(
        {
            "wan": str(config.get("wan_interface", "") or ""),
            "lan": lan,
            "prefix": prefix,
            "delegated": delegated_prefix.strip(),
            "reason": reason,
            "updated_at": _utc_now(),
        }
    )

    if prefix == previous and state.get("dnsmasq_prefix") == prefix:
        save_pd_state(state)
        return 0

    result = _write_dnsmasq_for_prefix(prefix)
    if result.ok:
        state["dnsmasq_prefix"] = prefix
        state["error"] = ""
    else:
        state["error"] = result.output
    save_pd_state(state)
    return 0 if result.ok else 1


