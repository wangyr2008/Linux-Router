# Prefix helpers
# ---------------------------------------------------------------------------


def _is_usable_global(value: str) -> bool:
    lowered = value.lower()
    return not lowered.startswith(("fe80:", "fd", "::"))


def first_lan_subnet(delegated: str) -> str:
    """Turn a delegated prefix into the /64 handed to the LAN.

    dhcpcd is configured with ``<lan>/0/64``, so the LAN always gets the first
    /64 of whatever the ISP delegated (/60, /56, or already a /64).
    """
    value = delegated.strip().split(",")[0].strip()
    if not value:
        return ""
    try:
        network = ipaddress.ip_network(value, strict=False)
    except ValueError:
        return ""
    if not isinstance(network, ipaddress.IPv6Network):
        return ""
    if network.prefixlen > PD_SUBNET_PREFIX:
        return ""
    if network.prefixlen == PD_SUBNET_PREFIX:
        return str(network)
    return str(next(network.subnets(new_prefix=PD_SUBNET_PREFIX)))


def derive_lan_prefix(lan_interface: str, delegated: str = "") -> str:
    """The delegation is authoritative; the kernel address is only a fallback.

    Order matters on a renumber: right after a new prefix arrives the old /64 can
    still be on the interface, and `ip` lists it first.
    """
    subnet = first_lan_subnet(delegated)
    if subnet:
        return subnet
    if not lan_interface:
        return ""
    addresses = get_interface_addresses(lan_interface).get("ipv6", [])
    for address in addresses:
        if not _is_usable_global(address):
            continue
        try:
            network = ipaddress.ip_interface(address).network
        except ValueError:
            continue
        if network.prefixlen == PD_SUBNET_PREFIX:
            return str(network)
    return ""


