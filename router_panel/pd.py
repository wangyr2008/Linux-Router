PD_SERVICE_NAME = "linux-router-pd.service"
PD_SERVICE_PATH = Path("/etc/systemd/system") / PD_SERVICE_NAME
PD_CONFIG_DIR = Path("/etc/linux-router")
PD_DHCPCD_CONF_PATH = PD_CONFIG_DIR / "dhcpcd.conf"
PD_HOOK_PATH = Path("/usr/lib/dhcpcd/dhcpcd-hooks/99-linux-router")
PD_STATE_PATH = DATA_DIR / "pd.json"
PD_HOOK_ENTRY = BASE_DIR / "pd_hook.py"
SYSTEM_DHCPCD_SERVICE = "dhcpcd.service"
PD_LEASE_SLA_ID = 0
PD_SUBNET_PREFIX = 64
PD_PREFIX_HINT = "::/56"

# Reasons where dhcpcd (re)assigned or dropped a delegated prefix.
PD_SYNC_REASONS = (
    "DELEGATED6",
    "BOUND6",
    "REBIND6",
    "REBOUND6",
    "RENEW6",
    "REBOOT6",
    "INFORM6",
    "ROUTERADVERT",
    "EXPIRE6",
    "STOP6",
    "STOPPED",
    "NOCARRIER",
    "DEPARTED",
)

# Reasons meaning the delegation is gone; the prefix must not be reused.
PD_LOSS_REASONS = frozenset({"EXPIRE6", "STOP6", "STOPPED", "NOCARRIER", "DEPARTED"})


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def dhcpcd_binary() -> str:
    return shutil.which("dhcpcd") or ""


def dhcpcd_available() -> bool:
    return bool(dhcpcd_binary())


