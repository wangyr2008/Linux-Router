def install_pd_client() -> CommandResult:
    """Install dhcpcd, which is optional and only needed for PD mode."""
    if dhcpcd_available():
        return CommandResult(True, "dhcpcd 已安装")
    if not command_exists("apt-get"):
        return CommandResult(False, "未找到 apt-get，请手动安装 dhcpcd")

    env = {
        "PATH": "/usr/sbin:/usr/bin:/sbin:/bin",
        "DEBIAN_FRONTEND": "noninteractive",
    }
    for package in ("dhcpcd", "dhcpcd-base"):
        installed = run_command(
            ["apt-get", "install", "-y", "--no-install-recommends", package],
            timeout=300,
            env=env,
        )
        if installed.ok and dhcpcd_available():
            return CommandResult(True, f"已安装 {package}")
    return CommandResult(False, "安装 dhcpcd 失败，请检查 apt 源或手动执行 apt install dhcpcd")


def _stop_conflicting_dhcpcd() -> bool:
    """Our own unit needs the pidfile; the distro unit would collide."""
    if not is_service_active(SYSTEM_DHCPCD_SERVICE) and not is_service_enabled(SYSTEM_DHCPCD_SERVICE):
        return False
    run_command(["systemctl", "disable", "--now", SYSTEM_DHCPCD_SERVICE], timeout=SYSTEM_COMMAND_TIMEOUT)
    return True


def enable_pd(config: dict[str, Any]) -> CommandResult:
    wan = str(config.get("wan_interface", "") or "")
    lan = str(config.get("lan_interface", "") or "")
    if not wan or not lan:
        return CommandResult(False, "PD 模式需要先选择 WAN 和 LAN 接口")
    if not dhcpcd_available():
        return CommandResult(False, "系统未安装 dhcpcd，请先在依赖页面安装 PD 客户端")

    stopped_system_unit = _stop_conflicting_dhcpcd()

    try:
        PD_CONFIG_DIR.mkdir(parents=True, exist_ok=True)
        atomic_write_text(PD_DHCPCD_CONF_PATH, render_dhcpcd_conf(config), mode=0o644)
        PD_HOOK_PATH.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_text(PD_HOOK_PATH, render_hook_script(config), mode=0o755)
        atomic_write_text(PD_SERVICE_PATH, render_service_unit(config), mode=0o644)
    except OSError as exc:
        return CommandResult(False, f"写入 PD 配置失败：{exc}")

    run_command(["systemctl", "daemon-reload"], timeout=SYSTEM_COMMAND_TIMEOUT)
    enabled = run_command(["systemctl", "enable", PD_SERVICE_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)
    if not enabled.ok:
        return CommandResult(False, f"启用 {PD_SERVICE_NAME} 失败：{enabled.output or '未知错误'}")
    started = run_command(["systemctl", "restart", PD_SERVICE_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)
    if not started.ok:
        return CommandResult(False, f"启动 {PD_SERVICE_NAME} 失败：{started.output or '未知错误'}")

    state = load_pd_state()
    state.update(
        {
            "wan": wan,
            "lan": lan,
            "stopped_system_dhcpcd": stopped_system_unit,
            "enabled_at": _utc_now(),
        }
    )
    save_pd_state(state)
    return CommandResult(True, f"PD 客户端已启动（{wan} 请求前缀，{lan} 接收 /64）")


def disable_pd() -> CommandResult:
    run_command(["systemctl", "disable", "--now", PD_SERVICE_NAME], timeout=SYSTEM_COMMAND_TIMEOUT)
    for path in (PD_SERVICE_PATH, PD_HOOK_PATH, PD_DHCPCD_CONF_PATH):
        try:
            path.unlink(missing_ok=True)
        except OSError:
            pass
    run_command(["systemctl", "daemon-reload"], timeout=SYSTEM_COMMAND_TIMEOUT)

    state = load_pd_state()
    if state.get("stopped_system_dhcpcd"):
        run_command(["systemctl", "enable", "--now", SYSTEM_DHCPCD_SERVICE], timeout=SYSTEM_COMMAND_TIMEOUT)

    lan = str(state.get("lan", "") or "")
    prefix = str(state.get("prefix", "") or "")
    if lan and prefix:
        run_command(["ip", "-6", "addr", "del", f"{prefix}1/64", "dev", lan], timeout=10)

    save_pd_state({})
    return CommandResult(True, "PD 客户端已停用")


