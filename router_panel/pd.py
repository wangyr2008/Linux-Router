def load_pd_state() -> dict[str, Any]:
    try:
        payload = json.loads(PD_STATE_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return payload if isinstance(payload, dict) else {}


def save_pd_state(state: dict[str, Any]) -> None:
    atomic_write_text(
        PD_STATE_PATH,
        json.dumps(state, ensure_ascii=False, indent=2) + "\n",
        mode=0o600,
    )


def lan_prefix() -> str:
    """Currently delegated /64 for the LAN, empty when nothing is delegated."""
    return str(load_pd_state().get("prefix", "") or "")


